import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import { BIBLE_BOOKS } from "../packages/shared/dist/bible/all.js"

const outputUrl = new URL(
  "../packages/shared/src/bible/catalog.generated.ts",
  import.meta.url,
)

const catalog = BIBLE_BOOKS.map((book) => ({
  id: book.id,
  name: book.name,
  testament: book.testament,
  order: book.order,
  blurb: book.blurb,
  chapters: book.chapters.map((chapter) => ({
    id: chapter.id,
    bookId: chapter.bookId,
    number: chapter.number,
    title: chapter.title,
    summary: chapter.summary,
    status: chapter.status,
  })),
}))

const source = `// Generated by scripts/generate-bible-catalog.mjs. Do not edit manually.
import type { BibleBookSummary } from "./types.js"

export const BIBLE_CATALOG = ${JSON.stringify(catalog, null, 2)} satisfies BibleBookSummary[]
`

const check = process.argv.includes("--check")
if (check) {
  const current = await readFile(outputUrl, "utf8").catch(() => "")
  if (current !== source) {
    console.error(
      "Catalogul Bibliei nu este sincronizat. Rulează pnpm generate:bible-catalog.",
    )
    process.exitCode = 1
  } else {
    const { loadAllBibleChapters } = await import(
      "../packages/shared/dist/bible/loaders.js"
    )
    const loadedKeys = new Set(
      (await loadAllBibleChapters()).map(
        (chapter) => `${chapter.bookId}:${chapter.number}`,
      ),
    )
    const catalogKeys = catalog.flatMap((book) =>
      book.chapters.map((chapter) => `${chapter.bookId}:${chapter.number}`),
    )
    const missing = catalogKeys.filter((key) => !loadedKeys.has(key))
    const extra = [...loadedKeys].filter((key) => !catalogKeys.includes(key))
    if (missing.length > 0 || extra.length > 0) {
      console.error(
        `Registrul de încărcare Biblia diferă de catalog. Lipsesc: ${missing.join(", ") || "-"}. În plus: ${extra.join(", ") || "-"}.`,
      )
      process.exitCode = 1
    } else {
      console.log(
        `Catalog Biblia sincronizat: ${catalog.length} cărți, ${loadedKeys.size} capitole încărcabile.`,
      )
    }
  }
} else {
  await writeFile(outputUrl, source)
  console.log(`Catalog Biblia generat: ${fileURLToPath(outputUrl)}`)
}
