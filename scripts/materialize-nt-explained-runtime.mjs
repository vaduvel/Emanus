#!/usr/bin/env node

import { createHash } from "node:crypto"
import { readFile, readdir, mkdir, writeFile, unlink } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const sourceDir = path.join(root, "docs/data/biblia-explicata/nt-final-source-first")
const manifestFile = path.join(root, "docs/data/biblia-explicata/nt-final-source-first-manifest.json")
const generatedDir = path.join(root, "packages/shared/src/bible/generated/ntExplainedSource")
const generatedIndex = path.join(root, "packages/shared/src/bible/generated/ntExplainedSource.ts")
const checkOnly = process.argv.includes("--check")
const expected = { books: 27, chapters: 260, units: 970 }

function fail(message) {
  throw new Error(`[NT explained materializer] ${message}`)
}

function normalizeBookId(id) {
  return id === "fapte" ? "faptele-apostolilor" : id
}

function normalizedUnitId(book, unitId) {
  if (book.id !== "fapte") return unitId
  return unitId.replace(/^fapte-/u, "faptele-apostolilor-")
}

function publicUnit(book, chapter, unit) {
  if (
    !Number.isInteger(unit.verseStart) ||
    !Number.isInteger(unit.verseEnd) ||
    unit.verseStart < 1 ||
    unit.verseEnd < unit.verseStart
  ) {
    fail(`${book.name} ${chapter.number}: interval invalid pentru ${unit.id}`)
  }
  if (typeof unit.teaching !== "string" || !unit.teaching.trim()) {
    fail(`${book.name} ${chapter.number}: teaching gol pentru ${unit.id}`)
  }
  if (unit.explanationKind !== "exposition" && unit.explanationKind !== "textual-overview") {
    fail(`${book.name} ${chapter.number}: explanationKind invalid pentru ${unit.id}`)
  }

  return {
    id: normalizedUnitId(book, unit.id),
    ref: unit.ref,
    verseStart: unit.verseStart,
    verseEnd: unit.verseEnd,
    heading: unit.heading,
    teaching: unit.teaching,
    explanationKind: unit.explanationKind,
    ...(Array.isArray(unit.words) && unit.words.length ? { words: unit.words } : {}),
    ...(Array.isArray(unit.crossRefs) && unit.crossRefs.length ? { crossRefs: unit.crossRefs } : {}),
    ...(typeof unit.forYourHeart === "string" && unit.forYourHeart.trim()
      ? { forYourHeart: unit.forYourHeart }
      : {}),
  }
}

function publicBook(book) {
  if (
    book.testament !== "nt" ||
    book.status !== "published" ||
    book.publicationReady !== true ||
    book.public !== true
  ) {
    fail(`${book.name ?? book.id}: corpusul nu este publicat`)
  }

  return {
    id: normalizeBookId(book.id),
    sourceId: book.bookId,
    name: book.name,
    order: book.order,
    blurb: book.chapters[0]?.summary ?? `Biblia Emanus explicată — ${book.name}.`,
    chapters: book.chapters.map((chapter) => {
      if (chapter.status !== "published") fail(`${book.name} ${chapter.number}: status nepublicat`)
      const lastVerse = chapter.emanusTextBinding?.lastVerseNumber
      if (!Number.isInteger(lastVerse) || lastVerse < 1) {
        fail(`${book.name} ${chapter.number}: lipsește limita canonică`)
      }

      const owners = new Map()
      const units = chapter.units.map((unit) => publicUnit(book, chapter, unit))
      for (const unit of units) {
        for (let verse = unit.verseStart; verse <= unit.verseEnd; verse += 1) {
          const current = owners.get(verse) ?? []
          current.push(unit.id)
          owners.set(verse, current)
        }
      }
      for (let verse = 1; verse <= lastVerse; verse += 1) {
        const matches = owners.get(verse) ?? []
        if (matches.length !== 1) {
          fail(`${book.name} ${chapter.number}:${verse} are ${matches.length} explicații (${matches.join(", ") || "niciuna"})`)
        }
      }

      return {
        number: chapter.number,
        title: chapter.title,
        summary: chapter.summary,
        literaryContext: chapter.literaryContext ?? "",
        historicalContext: chapter.historicalContext ?? "",
        prayer: chapter.prayer ?? "",
        units,
      }
    }),
  }
}

function moduleText(identifier, book) {
  return [
    "// Generated by scripts/materialize-nt-explained-runtime.mjs. Do not edit.",
    'import type { NtExplainedSourceBook } from "../../ntExplainedBinding.js"',
    "",
    `export const ${identifier}: NtExplainedSourceBook = ${JSON.stringify(book, null, 2)}`,
    "",
  ].join("\n")
}

async function expectOrWrite(file, content) {
  if (checkOnly) {
    let actual
    try {
      actual = await readFile(file, "utf8")
    } catch {
      fail(`lipsește ${path.relative(root, file)}`)
    }
    if (actual !== content) fail(`${path.relative(root, file)} este nematerializat sau stale`)
    return
  }
  let actual
  try {
    actual = await readFile(file, "utf8")
  } catch {
    actual = undefined
  }
  if (actual !== content) await writeFile(file, content, "utf8")
}

const manifest = JSON.parse(await readFile(manifestFile, "utf8"))
if (manifest.status !== "published" || manifest.publicationReady !== true) {
  fail("manifestul final nu este publicat")
}
if (
  manifest.counts?.books !== expected.books ||
  manifest.counts?.chapters !== expected.chapters ||
  manifest.counts?.units !== expected.units
) {
  fail(`manifest incomplet: ${JSON.stringify(manifest.counts)}`)
}

const files = (await readdir(sourceDir)).filter((file) => file.endsWith(".json")).sort()
if (files.length !== expected.books) fail(`cărți ${files.length}/${expected.books}`)
if (!Array.isArray(manifest.books) || manifest.books.length !== expected.books) {
  fail(`manifest cărți ${manifest.books?.length ?? 0}/${expected.books}`)
}

const manifestBooksById = new Map(manifest.books.map((book) => [book.id, book]))
const records = []
for (const file of files) {
  const raw = await readFile(path.join(sourceDir, file), "utf8")
  const source = JSON.parse(raw)
  const manifestBook = manifestBooksById.get(source.id)
  if (!manifestBook) fail(`${file}: carte absentă din manifest`)
  const sha256 = createHash("sha256").update(raw).digest("hex")
  if (sha256 !== manifestBook.sha256) fail(`${file}: sha256 diferă de manifest`)

  const book = publicBook(source)
  const units = book.chapters.reduce((total, chapter) => total + chapter.units.length, 0)
  if (
    manifestBook.order !== book.order ||
    manifestBook.bookId !== book.sourceId ||
    manifestBook.chapters !== book.chapters.length ||
    manifestBook.units !== units
  ) {
    fail(`${file}: metadatele diferă de manifest`)
  }
  records.push({ file, book })
}
records.sort((left, right) => left.book.order - right.book.order)
const books = records.map((record) => record.book)
const orders = books.map((book) => book.order)
if (orders.some((order, index) => order !== index + 40)) {
  fail(`ordine canonică invalidă: ${orders.join(", ")}`)
}

const chapterCount = books.reduce((total, book) => total + book.chapters.length, 0)
const unitCount = books.reduce(
  (total, book) => total + book.chapters.reduce((chapterTotal, chapter) => chapterTotal + chapter.units.length, 0),
  0,
)
if (chapterCount !== expected.chapters || unitCount !== expected.units) {
  fail(`totaluri ${books.length}/${expected.books} cărți, ${chapterCount}/${expected.chapters} capitole, ${unitCount}/${expected.units} unități`)
}

if (!checkOnly) await mkdir(generatedDir, { recursive: true })
const moduleNames = []
const identifiers = []
for (let index = 0; index < books.length; index += 1) {
  const sourceName = records[index].file.replace(/\.json$/u, "")
  const moduleName = `${sourceName}.ts`
  const identifier = `NT_EXPLAINED_SOURCE_${String(index + 1).padStart(2, "0")}`
  moduleNames.push(moduleName)
  identifiers.push(identifier)
  await expectOrWrite(path.join(generatedDir, moduleName), moduleText(identifier, books[index]))
}

if (!checkOnly) {
  const expectedModules = new Set(moduleNames)
  for (const existing of await readdir(generatedDir)) {
    if (existing.endsWith(".ts") && !expectedModules.has(existing)) {
      await unlink(path.join(generatedDir, existing))
    }
  }
}

const indexText = [
  "// Generated by scripts/materialize-nt-explained-runtime.mjs. Do not edit.",
  'import type { NtExplainedSourceBook } from "../ntExplainedBinding.js"',
  ...moduleNames.map(
    (moduleName, index) =>
      `import { ${identifiers[index]} } from "./ntExplainedSource/${moduleName.replace(/\.ts$/u, ".js")}"`,
  ),
  "",
  `export const NT_EXPLAINED_SOURCE_BOOKS: readonly NtExplainedSourceBook[] = [${identifiers.join(", ")}]`,
  `export const NT_EXPLAINED_SOURCE_COUNTS = ${JSON.stringify(expected)} as const`,
  "",
].join("\n")
await expectOrWrite(generatedIndex, indexText)

console.log(
  `[NT explained materializer] ${checkOnly ? "verificate" : "materializate"} ${books.length} cărți / ${chapterCount} capitole / ${unitCount} unități.`,
)
