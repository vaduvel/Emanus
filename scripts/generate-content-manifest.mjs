import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import {
  DOORS,
  EXPLORE_DOORS,
  PATHS,
  ROOMS,
  DOCTRINE_LESSONS,
} from "../packages/shared/dist/paths/index.js"
import {
  LIBRARY_LESSONS,
  SHELVES,
} from "../packages/shared/dist/library/current.js"
import {
  enrichLessonCollection,
} from "../packages/shared/dist/interactionEnrichment.js"

const outputUrl = new URL(
  "../packages/shared/src/contentCatalog.generated.ts",
  import.meta.url,
)

function lessonSummary(lesson) {
  const memoryStep = lesson.steps.find(
    (step) => step.type === "memory_verse" && step.scripture,
  )

  return {
    id: lesson.id,
    courseId: lesson.courseId,
    order: lesson.order,
    title: lesson.title,
    estMinutes: lesson.estMinutes,
    memoryVerse: memoryStep?.scripture ?? null,
  }
}

const rawLessons = new Map()
for (const lesson of [
  ...PATHS.flatMap((path) => path.lessons),
  ...DOCTRINE_LESSONS,
  ...LIBRARY_LESSONS,
]) {
  rawLessons.set(lesson.id, lesson)
}

const ageHints = Object.fromEntries(
  SHELVES.flatMap((shelf) =>
    shelf.courses.map((course) => [course.id, course.ageHint]),
  ),
)
const versionedLessons = new Map(
  enrichLessonCollection([...rawLessons.values()], ageHints).map((lesson) => [
    lesson.id,
    lesson,
  ]),
)

const payload = {
  schemaVersion: 1,
  rooms: ROOMS,
  doors: DOORS,
  exploreDoors: EXPLORE_DOORS,
  paths: PATHS.map((path) => ({
    id: path.id,
    roomId: path.roomId,
    title: path.title,
    promise: path.promise,
    lessons: path.lessons.map((lesson) =>
      lessonSummary(versionedLessons.get(lesson.id) ?? lesson),
    ),
    practices: path.practices,
  })),
  doctrineLessons: DOCTRINE_LESSONS.map((lesson) =>
    lessonSummary(versionedLessons.get(lesson.id) ?? lesson),
  ),
  shelves: SHELVES.map((shelf) => ({
    id: shelf.id,
    title: shelf.title,
    blurb: shelf.blurb,
    gated: shelf.gated ?? false,
    courses: shelf.courses.map((course) => ({
      ...course,
      lessons: course.lessonIds
        .map((lessonId) => versionedLessons.get(lessonId))
        .filter(Boolean)
        .map(lessonSummary),
    })),
  })),
}

const contentVersion = createHash("sha256")
  .update(
    JSON.stringify({
      manifest: payload,
      lessons: [...versionedLessons.values()].sort((a, b) =>
        a.id.localeCompare(b.id),
      ),
    }),
  )
  .digest("hex")
  .slice(0, 16)

const source = `// Generated by scripts/generate-content-manifest.mjs. Do not edit manually.
export const GENERATED_CONTENT_MANIFEST = ${JSON.stringify(
  { ...payload, contentVersion },
  null,
  2,
)} as const
`

const check = process.argv.includes("--check")
const outputPath = fileURLToPath(outputUrl)

if (check) {
  const current = await readFile(outputUrl, "utf8").catch(() => "")
  if (current !== source) {
    console.error(
      "Manifestul de conținut nu este sincronizat. Rulează pnpm generate:content-manifest.",
    )
    process.exitCode = 1
  } else {
    console.log(`Manifest sincronizat: ${contentVersion}`)
  }
} else {
  await writeFile(outputUrl, source)
  console.log(`Manifest generat: ${outputPath} (${contentVersion})`)
}
